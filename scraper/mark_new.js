#!/usr/bin/env node
/*
 * mark_new.js — build data/new_ids.js (powers the NEW / UPDATED badges in the dashboard)
 *
 * It diffs the CURRENT data/raw/wiki_en.json against the version stored in a git ref
 * (the last data you committed before re-scraping) and lists what is new / changed.
 *
 * Usage (after `python scraper/scrape_nightcamp.py`, BEFORE committing):
 *   node scraper/mark_new.js            # compare with HEAD (last commit)
 *   node scraper/mark_new.js 04bf8dc    # compare with any commit / tag / branch
 */
const cp = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const ref = process.argv[2] || 'HEAD';
const rawPath = path.join(root, 'data', 'raw', 'wiki_en.json');

const old = JSON.parse(
  cp.execSync(`git show ${ref}:data/raw/wiki_en.json`, { cwd: root, maxBuffer: 1 << 30 }).toString('utf8')
);
const cur = JSON.parse(fs.readFileSync(rawPath, 'utf8'));

const idSet = (arr) => new Set((arr || []).map((x) => x.id));
const newOf = (key) => {
  const o = idSet(old[key]);
  return (cur[key] || []).filter((x) => !o.has(x.id)).map((x) => x.id);
};

const oldSkills = new Set();
(old.jobs || []).forEach((j) => (j.sk || []).forEach((s) => oldSkills.add(s.id)));
const newSkills = [];
(cur.jobs || []).forEach((j) => (j.sk || []).forEach((s) => { if (!oldSkills.has(s.id)) newSkills.push(s.id); }));

const oldRunes = (old.s2 && old.s2.runes && old.s2.runes.list) || {};
const curRunes = (cur.s2 && cur.s2.runes && cur.s2.runes.list) || {};
const oldCards = new Set((((old.s2 || {}).lore || {}).arts || []).map((a) => a.t));

// monsters whose drops changed (materials, gear, rune) -> "UPDATED"
const oldMon = {};
(old.monsters || []).forEach((m) => { oldMon[m.id] = m; });
const updatedMonsters = [];
(cur.monsters || []).forEach((m) => {
  const o = oldMon[m.id];
  if (!o) return;
  const sig = (x) => JSON.stringify([x.mats, x.drops, x.rune]);
  if (sig(o) !== sig(m)) updatedMonsters.push(m.id);
});

// extra rune drop tables added/changed (fireDrop, lowDrop, gunDrop...)
const runeTables = ['gunDrop', 'fireDrop', 'lowDrop'];
const oldR = (old.s2 && old.s2.runes) || {};
const curR = (cur.s2 && cur.s2.runes) || {};
const runeDropChanged = [];
runeTables.forEach((t) => {
  Object.keys(curR[t] || {}).forEach((rid) => {
    if (JSON.stringify((oldR[t] || {})[rid]) !== JSON.stringify(curR[t][rid])) runeDropChanged.push(rid);
  });
});

const out = {
  since: ref,
  at: new Date().toISOString().slice(0, 10),
  items: newOf('items'),
  materials: newOf('materials'),
  monsters: newOf('monsters'),
  maps: newOf('maps'),
  jobs: newOf('jobs'),
  quests: newOf('quests'),
  sets: newOf('sets'),
  skills: newSkills,
  runes: Object.keys(curRunes).filter((k) => !(k in oldRunes)),
  cards: ((((cur.s2 || {}).lore || {}).arts) || []).filter((a) => !oldCards.has(a.t)).map((a) => a.t),
  updatedMonsters,
  runeDropChanged: Array.from(new Set(runeDropChanged))
};

const file = path.join(root, 'data', 'new_ids.js');
fs.writeFileSync(file, `/* generated by scraper/mark_new.js — do not edit by hand */\nwindow.NEW_IDS = ${JSON.stringify(out)};\n`, 'utf8');

const summary = Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Array.isArray(v) ? v.length : v]));
console.log('Wrote data/new_ids.js', summary);
